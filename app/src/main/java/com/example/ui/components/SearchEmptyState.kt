import androidx.compose.ui.unit.dp

/** Shown when a search has no hits, so it is never confused with "nothing synced yet". */
@Composable
fun SearchEmptyState(query: String, onClear: () -> Unit) {
    Column(
        modifier = Modifier.fillMaxWidth().padding(vertical = 48.dp, horizontal = 24.dp),
        horizontalAlignment = Alignment.CenterHorizontally,
        verticalArrangement = Arrangement.spacedBy(10.dp)
    ) {
        Icon(
            Icons.Filled.SearchOff,
            contentDescription = null,
            tint = MaterialTheme.colorScheme.onSurfaceVariant,
            modifier = Modifier.size(40.dp)
        )
        Text(
            text = "Nothing matches “$query”",
            style = MaterialTheme.typography.titleMedium,
            textAlign = TextAlign.Center
        )
        Text(
            text = "Try part of a name, a company, or the last digits of a number.",
            style = MaterialTheme.typography.bodyMedium,
            color = MaterialTheme.colorScheme.onSurfaceVariant,
            textAlign = TextAlign.Center
        )
        Spacer(Modifier.height(4.dp))
        OutlinedButton(onClick = onClear, modifier = Modifier.testTag("search_empty_clear")) {
            Text("Clear search")
        }
    }
}
